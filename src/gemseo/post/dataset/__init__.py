"""Datasets post-processing.

A [DatasetPlot][gemseo.post.dataset.base.BaseDatasetPlot] is a generic graphical
representation of a [Dataset][gemseo.dataset.dataset.Dataset]
that can be displayed on screen or saved to a file.
The different visualization tools
([BasePost][gemseo.post.core.base_post.BasePost],
[BaseSensitivityAnalysis.plot()][gemseo.uncertainty.sensitivity.core.base.BaseSensitivityAnalysis.plot],
...)
proposed by GEMSEO rely more and more on it
to factorize the code,
separate data and graph generation
and standardize the visualizations.

As an example,
[RadarChart][gemseo.post.dataset.radar_chart.RadarChart] implements a
[radar chart](https://en.wikipedia.org/wiki/Radar_chart)
and is used by both
[ConstraintRadar][gemseo.post.constraint_radar.ConstraintRadar]
to visualize the constraints stored in a
[Database][gemseo.core.problem.database.Database]
and
[plot_radar()][gemseo.uncertainty.sensitivity.core.base.BaseSensitivityAnalysis.plot_radar]
to visualize the sensitivity indices generated by a
[BaseSensitivityAnalysis][gemseo.uncertainty.sensitivity.core.base.BaseSensitivityAnalysis].
"""

